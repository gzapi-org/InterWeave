//! The human client's reference views (plan §17 (8)): Slint components
//! bound to `ui-model`, agreed with rust-ui-dev before they were built
//! (relay seqs 10823, 10826, 10849; the input queue 10867, 10870, 10879,
//! 10882, 10885).
//!
//! A view reads a [`UiModel`] and nothing else, and a person's actions
//! leave it as [`ViewEvent`]s -- it never calls the facade, the store or
//! IPC. A Slint callback cannot see the model, so it decides nothing: it
//! queues what the person pressed, by identity, and [`View::take_events`]
//! resolves each press against the model it is handed then.
